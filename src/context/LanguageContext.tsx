export interface LanguageContextProps {
  language: SupportedLanguageCode;
  languageCode: SupportedLanguageCode;
  currentLanguage: string;
  setLanguage: (code: SupportedLanguageCode) => void;
  currentLanguageMeta: LanguageMeta;
  supportedLanguages: LanguageMeta[];
  t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextProps | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<SupportedLanguageCode>(() => {
    try {
      const stored = localStorage.getItem('sahay_ai_lang');
      if (stored && SUPPORTED_LANGUAGES.some((l) => l.code === stored)) {
        return stored as SupportedLanguageCode;
      }
    } catch {
      // fallback
    }
    return 'en';
  });

  const setLanguage = (code: SupportedLanguageCode) => {
    setLanguageState(code);
    try {
      localStorage.setItem('sahay_ai_lang', code);
    } catch {
      // ignored
    }
  };

  const currentLanguageMeta =
    SUPPORTED_LANGUAGES.find((l) => l.code === language) || SUPPORTED_LANGUAGES[0];

  const t = (key: string): string => {
    const item = TRANSLATIONS[key];
    if (!item) return key;
    return item[language] || item['en'] || key;
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        languageCode: language,
        currentLanguage: currentLanguageMeta.name,
        setLanguage,
        currentLanguageMeta,
        supportedLanguages: SUPPORTED_LANGUAGES,
        t,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export function useLanguage(): LanguageContextProps {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
